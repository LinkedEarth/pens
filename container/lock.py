#!/usr/bin/env python
"""Regenerate container/environment.yml, the pinned (linux-64) environment used
to build the pens container image, from the hand-edited ./environment.yml.

    python container/lock.py

Requires conda (any platform; the solve is done for linux-64) and network access
to GitHub and PyPI. Afterwards, commit both files; the build-container workflow
builds the image from the lock and runs every notebook inside it.

How the lock is made: the spec is solved for linux-64 and every resolved conda
package (direct and transitive) is pinned to its exact version; pip packages are
pinned to their current version on PyPI. repo2docker installs this on top of its
own base environment (fixed by the repo2docker version), upgrading base packages
where the lock requires it.
"""
import datetime
import json
import os
import subprocess
import sys
import urllib.request
from pathlib import Path

import yaml

# keep in sync with FORCE_REPO2DOCKER_VERSION in .github/workflows/build-container.yml
REPO2DOCKER_VERSION = "2026.04.0"

ROOT = Path(__file__).resolve().parents[1]
SPEC = ROOT / "environment.yml"
LOCK = ROOT / "container" / "environment.yml"


def parse_spec():
    spec = yaml.safe_load(SPEC.read_text())
    conda = [d for d in spec["dependencies"] if isinstance(d, str)]
    pip = next((d["pip"] for d in spec["dependencies"] if isinstance(d, dict)), [])
    python = next(s.split("=", 1)[1] for s in conda if s.startswith("python="))
    return spec["channels"], conda, pip, python


def solve_linux(channels, specs):
    env = dict(os.environ, CONDA_SUBDIR="linux-64", CONDA_OVERRIDE_GLIBC="2.28")
    cmd = ["conda", "create", "--name", "pens-lock-dryrun", "--dry-run", "--json",
           "--override-channels"]
    for c in channels:
        cmd += ["-c", c]
    out = subprocess.run(cmd + specs, env=env, capture_output=True, text=True)
    res = json.loads(out.stdout)
    if "actions" not in res:
        sys.exit("Solve failed:\n" + res.get("message", out.stdout + out.stderr))
    return {p["name"]: p["version"] for p in res["actions"]["LINK"]}


def pypi_latest(name):
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/json") as r:
        return json.load(r)["info"]["version"]


def main():
    channels, conda_specs, pip_specs, _python = parse_spec()
    solved = solve_linux(channels, conda_specs)
    pinned = [f"{n}={v}" for n, v in sorted(solved.items()) if n != "python"]
    pip_pinned = [s if "==" in s else f"{s}=={pypi_latest(s)}" for s in pip_specs]

    header = (
        f"# GENERATED by container/lock.py on {datetime.date.today()} -- do not edit by hand.\n"
        "# Edit ./environment.yml instead, then rerun:  python container/lock.py\n"
        f"# Platform: linux-64; built on top of the repo2docker {REPO2DOCKER_VERSION} base env.\n"
    )
    body = {
        "name": "pens",
        "channels": channels,
        "dependencies": [f"python={solved['python']}"] + pinned + [{"pip": pip_pinned}],
    }
    LOCK.write_text(header + yaml.safe_dump(body, sort_keys=False, default_flow_style=False))
    print(f"Wrote {LOCK.relative_to(ROOT)}: python {solved['python']}, "
          f"{len(pinned)} pinned conda packages, "
          f"pip: {', '.join(pip_pinned)}")
    for k in ["numpy", "scipy", "pandas", "matplotlib", "xarray"]:
        print(f"  {k} {solved.get(k)}")


if __name__ == "__main__":
    main()
